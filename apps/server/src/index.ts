import { backfillDecisionReports, saveDecisionReport } from "./modules/reports/service.js";
import { buildApp } from "./app.js";
import { loadConfig } from "./config.js";
import { createDatabase } from "./db/client.js";
import { EventHub } from "./http/sse.js";
import { startMarketServices } from "./modules/market/service.js";
import { AgentService } from "./modules/agent/service.js";
import { BinanceMarketDataProvider } from "./modules/market/ingestion.js";
import { PaperExecutionProvider } from "./modules/execution/paper.js";
import { TradingTeamProvider } from "./providers/team.js";
import { TeamRuntime } from "./modules/team/runtime.js";

const config = loadConfig();
const { pool, db } = createDatabase(config.DATABASE_URL);
const events = new EventHub();
const market = new BinanceMarketDataProvider();
const { stop: stopMarket } = startMarketServices(pool, events, market);
const team = new TeamRuntime(pool, new TradingTeamProvider(config.XAI_API_KEY, config.OPENAI_API_KEY), events);
const agent = new AgentService({ pool, providers: { grok: team, codex: team }, decisionTimeoutMs: 180_000, onPause: (id) => team.cancelSimulation(id), execution: new PaperExecutionProvider(pool, market), onDecision: async (record) => { await team.recordDecision(record); await saveDecisionReport(pool, record.id).catch((error: unknown) => console.error("Decision report save failed; recovery will retry", error)); events.publish({ id: crypto.randomUUID(), type: "decision", occurredAt: new Date().toISOString(), simulationId: record.simulationId, data: record }); } });
await agent.recoverOnStartup();
await team.recover();
await backfillDecisionReports(pool);
let reporting = false;
const reportTimer = setInterval(() => {
  if (reporting) return;
  reporting = true;
  void backfillDecisionReports(pool).catch((error: unknown) => console.error("Report recovery failed", error)).finally(() => { reporting = false; });
}, 30_000);
reportTimer.unref();
team.onIdle = () => agent.scheduleAfterDiscussion();
team.start();
const app = buildApp(pool, events, { db, agent, team });
app.addHook("onClose", async () => { clearInterval(reportTimer); stopMarket(); });
app.addHook("onClose", async () => { await team.close(); await agent.close(); });
app.addHook("onClose", async () => pool.end());
await app.listen({ host: config.HOST, port: config.PORT });
